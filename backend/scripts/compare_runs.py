"""Summarise typed-question runs side by side; never calls a model.

Usage: uv run python scripts/compare_runs.py --scores ../docs/eval/model-comparison-scores.json
       --out ../docs/eval/model-comparison-metrics.md RUN.jsonl [RUN.jsonl ...]
Automatic metrics come from each run's rows (outcome, Analyst attempts and rejections,
latency, model calls). Hand scores come from the scores file, keyed by run file name; a run
without hand scores gets the automatic metrics only.
"""

import argparse
import json
import statistics
from collections import Counter
from pathlib import Path

# The right move for these is to clarify, decline or correct the question; the rest need a
# real answer (docs/eval/typed-questions-90-results.md).
BEHAVIOUR_KINDS = {"ambiguous", "hostile", "identity_conflict", "out_of_scope", "request_limits",
                   "unknown_entity", "unsupported", "var_false_premise"}
FALSE_PREMISE_IDS = {"d02", "c04"}


def group(row: dict) -> str:
    behaviour = row["kind"] in BEHAVIOUR_KINDS or row["id"] in FALSE_PREMISE_IDS
    return "behaviour" if behaviour else "answerable"


def automatic(rows: list[dict]) -> dict:
    seconds = sorted(r["seconds"] for r in rows)
    checks = Counter()
    for r in rows:
        for rejection in (r.get("analyst") or {}).get("rejections") or []:
            for line in rejection.splitlines():
                if line.startswith("- [") and "]" in line:
                    checks[line[3:line.index("]")]] += 1
    analyst = [r["analyst"] for r in rows if (r.get("analyst") or {}).get("source")]
    tokens = {}
    if all("usage" in r for r in rows):  # runs from before token logging have none
        u = [r["usage"] for r in rows]
        tokens = {"tokens_input": sum(x["input"] for x in u),
                  "tokens_output": sum(x["output"] for x in u),
                  "tokens_reasoning": sum(x["reasoning"] for x in u),
                  "max_reasoning_one_run": max(x["max_reasoning"] for x in u),
                  "runs_cut_off_by_token_limit": sum(x["length_stops"] for x in u)}
    return {
        "cases": len(rows),
        "model_calls": sum(r["calls"] for r in rows),
        "latency_median_s": round(statistics.median(seconds), 2),
        "latency_p90_s": seconds[int(0.9 * len(seconds))],
        "outcomes": dict(Counter(r["outcome"] for r in rows).most_common()),
        "analyst_runs": len(analyst),
        "analyst_first_attempt": sum(a["source"] == "llm" and a["attempts"] == 1 for a in analyst),
        "analyst_template": sum(a["source"] == "template" for a in analyst),
        "rejections_by_check": dict(checks.most_common()),
        **tokens,
    }


def hand(rows: list[dict], scores: dict) -> dict:
    out = {"answerable": Counter(), "behaviour": Counter()}
    for r in rows:
        s = scores[r["id"]]
        if group(r) == "answerable":
            out["answerable"]["cases"] += 1
            out["answerable"]["relevant"] += s["relevance"] == "pass"
            if s["grounding"] != "n/a":
                out["answerable"]["grounding_scored"] += 1
                out["answerable"]["grounded"] += s["grounding"] == "pass"
        else:
            out["behaviour"]["cases"] += 1
            out["behaviour"][s["behaviour"]] += 1
    a, b = out["answerable"], out["behaviour"]
    strict = sum(scores[r["id"]]["relevance"] == "pass" and scores[r["id"]]["grounding"] != "fail"
                 for r in rows if group(r) == "answerable") + b["correct"]
    return {"answerable": dict(a), "behaviour": dict(b),
            "handled": a["relevant"] + b["correct"], "strict": strict}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("runs", nargs="+", type=Path)
    ap.add_argument("--scores", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    scores = json.loads(args.scores.read_text(encoding="utf-8"))["runs"]
    lines = ["# Typed-question runs: metrics", "",
             f"Generated by `scripts/compare_runs.py` from {len(args.runs)} run(s).", ""]
    for path in args.runs:
        rows = [json.loads(s) for s in path.read_text(encoding="utf-8").splitlines() if s.strip()]
        meta = json.loads(path.with_suffix(".meta.json").read_text(encoding="utf-8"))
        auto = automatic(rows)
        lines += [f"## {path.name}", "",
                  (f"Model `{meta.get('deployment')}`, commit `{meta['commit']}`"
                  f"{' (dirty)' if meta.get('dirty') else ''}, questions "
                  f"`{meta['questions']['file']}` `{meta['questions']['sha']}`."), "",
                  "| Automatic | |", "|---|---|"]
        lines += [f"| {k} | {v} |" for k, v in auto.items()]
        if path.name in scores:
            h = hand(rows, scores[path.name]["cases"])
            lines += ["", "| Hand-scored | |", "|---|---|",
                      f"| Answerable relevant | {h['answerable']['relevant']} / {h['answerable']['cases']} |",
                      f"| Answerable grounded | {h['answerable']['grounded']} / {h['answerable']['grounding_scored']} |",
                      (f"| Behaviour correct / weak / wrong | {h['behaviour'].get('correct', 0)} / "
                      f"{h['behaviour'].get('weak', 0)} / {h['behaviour'].get('wrong', 0)} of "
                      f"{h['behaviour']['cases']} |"),
                      f"| Relevant answer or correct behaviour | {h['handled']} / {len(rows)} |",
                      f"| Strict (answerable also grounded) | {h['strict']} / {len(rows)} |"]
        lines.append("")
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
